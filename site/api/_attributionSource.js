// _attributionSource.js  --  the ONE provider the attribute function reads.
//
// Today it serves from the REAL precomputed cache site/data/attribution.json,
// produced in-session by scripts/build-attribution.mjs walking live tails through
// the Tensorust Ontology MCP (FAA registry + SEC subsidiaries + USAspending +
// Senate LDA). Tomorrow, if a runtime key or an internal proxy becomes available
// (see the blocker reported to Claude), only resolveAircraft() changes to call
// that REST/proxy instead; api/attribute.js and the whole UI stay untouched.
//
// REAL DATA ONLY. This provider never fabricates: a cache miss returns null, and
// the attribute function reports that honestly rather than guessing an owner.

// The cache is imported as a bundled ES module (generated by the build step), not
// read from disk at request time: Vercel compiles API functions from ESM to
// CommonJS, which would break a createRequire / import.meta.url JSON read, whereas
// a plain module import compiles cleanly and is always bundled. The static
// site/data/attribution.json still exists for the aggregate fleet/power view.
import ATTRIBUTION from "./_attributionData.js";

const DATA = ATTRIBUTION && ATTRIBUTION.byHex ? ATTRIBUTION : { meta: {}, byHex: {}, byTail: {} };

const BY_HEX = DATA.byHex || {};
const BY_TAIL = DATA.byTail || {};

// Resolve one aircraft from the cache. Hex is preferred (the map already has it);
// tail is the fallback / explicit key. Returns { provider, record|null }.
export function resolveAircraft({ hex, tail }) {
  if (hex) {
    const h = String(hex).trim().toUpperCase().replace(/^0X/, "");
    if (BY_HEX[h]) return { provider: "cache", record: BY_HEX[h] };
  }
  if (tail) {
    const t = String(tail).trim().toUpperCase();
    if (BY_TAIL[t]) return { provider: "cache", record: BY_TAIL[t] };
  }
  return { provider: "cache", record: null };
}

export function datasetMeta() {
  return DATA.meta || {};
}
