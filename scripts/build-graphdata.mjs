// build-graphdata.mjs  --  bundle site/data/graph.json into site/api/_graphData.js
// as an ES module, mirroring scripts/build-attribution.mjs -> _attributionData.js.
//
// WHY: Vercel compiles API functions from ESM to CommonJS. A JSON file read at
// request time (fs / import.meta.url / JSON import assertion) breaks that compile,
// but a plain `import X from "./_graphData.js"` bundles cleanly. So the deployed
// site/api/graph.js reads this generated module, never the raw JSON at runtime.
//
// This step INVENTS NOTHING. It copies the real graph verbatim and refuses to
// emit if the graph is not internally sound: every edge must reference nodes that
// exist and must carry an evidence string (the public source for that relation).
// Run after the graph builder (scripts/build-graph.mjs) refreshes graph.json.
//
//   node scripts/build-graphdata.mjs

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const SRC = join(here, "..", "site", "data", "graph.json");
const OUT = join(here, "..", "site", "api", "_graphData.js");

const graph = JSON.parse(readFileSync(SRC, "utf8"));

// ---- integrity gate: real, sourced, self-consistent, or we do not ship ----
const nodes = Array.isArray(graph.nodes) ? graph.nodes : [];
const edges = Array.isArray(graph.edges) ? graph.edges : [];
const ids = new Set(nodes.map((n) => n.id));
const problems = [];

if (!nodes.length) problems.push("no nodes");
const dupe = new Set();
for (const n of nodes) {
  if (!n.id) problems.push("node with no id");
  if (dupe.has(n.id)) problems.push("duplicate node id: " + n.id);
  dupe.add(n.id);
  if (!n.type) problems.push("node missing type: " + n.id);
  if (!n.label) problems.push("node missing label: " + n.id);
}
let edgesNoEvidence = 0;
for (const e of edges) {
  if (!ids.has(e.source)) problems.push("edge source not a node: " + e.source);
  if (!ids.has(e.target)) problems.push("edge target not a node: " + e.target);
  if (!e.kind) problems.push("edge missing kind: " + e.source + "->" + e.target);
  if (!e.evidence || !String(e.evidence).trim()) {
    edgesNoEvidence++;
    problems.push("edge missing evidence (public source): " + e.source + " -" + e.kind + "-> " + e.target);
  }
}

if (problems.length) {
  console.error("REFUSING to emit _graphData.js. The graph is not sound:");
  for (const p of problems.slice(0, 40)) console.error("  - " + p);
  if (problems.length > 40) console.error("  ... and " + (problems.length - 40) + " more");
  process.exit(1);
}

// ---- derived, real-only index: aircraft tail -> owning org node id ----
// Built ONLY from each owner node's own resolved_tails (produced by the ontology
// resolver). No fuzzy matching, no invention: a tail maps to a node only if that
// node already lists it. Lets the aircraft dossier open the right node directly.
const tailToOwner = {};
for (const n of nodes) {
  const tails = n.props && Array.isArray(n.props.resolved_tails) ? n.props.resolved_tails : [];
  for (const t of tails) {
    const key = String(t).trim().toUpperCase();
    if (key) tailToOwner[key] = n.id;
  }
}

const bundled = { ...graph, tail_to_owner: tailToOwner };

const banner =
  "// AUTO-GENERATED by scripts/build-graphdata.mjs. Do not edit by hand.\n" +
  "// REAL Tensorust Ontology connection graph, bundled as an ES module so the\n" +
  "// Vercel function can import it after the ESM->CommonJS compile. Every edge\n" +
  "// cites a public source; integrity-checked at build time. Rebuild to refresh.\n";

writeFileSync(OUT, banner + "export default " + JSON.stringify(bundled) + ";\n", "utf8");

console.log(
  "Wrote " + OUT + "\n  nodes=" + nodes.length +
  " edges=" + edges.length +
  " edges_without_evidence=" + edgesNoEvidence +
  " tail_index=" + Object.keys(tailToOwner).length
);
